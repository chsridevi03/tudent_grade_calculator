print("================================")
print("     STUDENT GRADE CALCULATOR")
print("================================")

name = input("Enter Student Name: ")

subjects = ["Python", "Mathematics", "English", "Science", "Computer Science"]

total = 0
pass_status = True

for subject in subjects:
    marks = float(input("Enter marks in " + subject + ": "))

    if marks < 0 or marks > 100:
        print("Invalid marks! Enter marks between 0 and 100.")
        exit()

    total = total + marks

    if marks < 35:
        pass_status = False

percentage = total / 5

if not pass_status:
    grade = "F"
    result = "FAIL"
elif percentage >= 90:
    grade = "A+"
    result = "PASS"
elif percentage >= 80:
    grade = "A"
    result = "PASS"
elif percentage >= 70:
    grade = "B"
    result = "PASS"
elif percentage >= 60:
    grade = "C"
    result = "PASS"
elif percentage >= 50:
    grade = "D"
    result = "PASS"
else:
    grade = "E"
    result = "PASS"

print("\n========== RESULT ==========")
print("Student Name:", name)
print("Total Marks:", total, "/ 500")
print("Percentage:", percentage, "%")
print("Grade:", grade)
print("Result:", result)
print("============================")